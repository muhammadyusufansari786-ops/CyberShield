function escJsStr(raw) {
  return DQ + raw.replace(/[\\"\\x00-\\x1f]/g, (c) => {
    if (c === DQ) return "\\\"";
    if (c === BS) return "\\\\";
    const code = c.charCodeAt(0);
    if (code < 0x10) return "\\x0" + code.toString(16);
    return "\\x" + code.toString(16);
  }) + DQ;
}

